-- No vendor tablespaces, identities, BOOLEAN, JSON, or generated values.
CREATE TABLE PRODUCT (
    PRODUCT_ID CHAR(4) NOT NULL,
    PRODUCT_NAME VARCHAR(32) NOT NULL,
    CURRENCY CHAR(3) NOT NULL CHECK (CURRENCY = 'ZZZ'),
    PRIMARY KEY (PRODUCT_ID)
);
CREATE TABLE CUSTOMER (
    CUSTOMER_ID CHAR(7) NOT NULL,
    DISPLAY_NAME CHAR(24) NOT NULL,
    FULL_NAME VARCHAR(64) NOT NULL,
    CUSTOMER_KIND CHAR(1) NOT NULL CHECK (CUSTOMER_KIND IN ('P', 'B')),
    OPEN_DATE DATE NOT NULL,
    STATUS CHAR(1) NOT NULL CHECK (STATUS IN ('A', 'D')),
    PRIMARY KEY (CUSTOMER_ID)
);
CREATE TABLE CUSTOMER_ADDRESS (
    CUSTOMER_ID CHAR(7) NOT NULL,
    ADDRESS_SEQ SMALLINT NOT NULL,
    STREET CHAR(24) NOT NULL,
    CITY CHAR(16) NOT NULL,
    DELIVERY_NOTE VARCHAR(8),
    PRIMARY KEY (CUSTOMER_ID, ADDRESS_SEQ),
    FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER (CUSTOMER_ID),
    CHECK (ADDRESS_SEQ BETWEEN 1 AND 99)
);
CREATE TABLE RATE_TABLE (
    PRODUCT_ID CHAR(4) NOT NULL,
    EFFECTIVE_DATE DATE NOT NULL,
    ANNUAL_RATE DECIMAL(5,4) NOT NULL,
    PRIMARY KEY (PRODUCT_ID, EFFECTIVE_DATE),
    FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT (PRODUCT_ID),
    CHECK (ANNUAL_RATE BETWEEN 0 AND 1)
);
CREATE TABLE ACCOUNT (
    ACCOUNT_NO CHAR(10) NOT NULL,
    CUSTOMER_ID CHAR(7) NOT NULL,
    PRODUCT_ID CHAR(4) NOT NULL,
    BALANCE DECIMAL(11,2) NOT NULL,
    ANNUAL_RATE DECIMAL(5,4) NOT NULL,
    OPEN_DATE DATE NOT NULL,
    STATUS CHAR(1) NOT NULL CHECK (STATUS IN ('A', 'D')),
    PRIMARY KEY (ACCOUNT_NO),
    FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER (CUSTOMER_ID),
    FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT (PRODUCT_ID),
    CHECK (ACCOUNT_NO LIKE '99Q%')
);
CREATE TABLE ACCOUNT_HOLDER (
    ACCOUNT_NO CHAR(10) NOT NULL,
    CUSTOMER_ID CHAR(7) NOT NULL,
    HOLDER_ROLE CHAR(1) NOT NULL CHECK (HOLDER_ROLE IN ('P', 'J')),
    PRIMARY KEY (ACCOUNT_NO, CUSTOMER_ID),
    FOREIGN KEY (ACCOUNT_NO) REFERENCES ACCOUNT (ACCOUNT_NO),
    FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER (CUSTOMER_ID)
);
CREATE TABLE PAYMENT_BATCH (
    BATCH_ID CHAR(7) NOT NULL,
    BUSINESS_DATE DATE NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL,
    STATUS CHAR(1) NOT NULL CHECK (STATUS IN ('O', 'C')),
    PRIMARY KEY (BATCH_ID)
);
CREATE TABLE "TRANSACTION" (
    TXN_ID CHAR(9) NOT NULL,
    ACCOUNT_NO CHAR(10) NOT NULL,
    POSTED_DATE DATE NOT NULL,
    AMOUNT DECIMAL(9,2) NOT NULL,
    TXN_TYPE CHAR(1) NOT NULL CHECK (TXN_TYPE IN ('P', 'F', 'I')),
    DETAIL CHAR(12) NOT NULL,
    PRIMARY KEY (TXN_ID),
    FOREIGN KEY (ACCOUNT_NO) REFERENCES ACCOUNT (ACCOUNT_NO)
);
CREATE TABLE PAYMENT (
    PAYMENT_ID CHAR(9) NOT NULL,
    TXN_ID CHAR(9) NOT NULL,
    BATCH_ID CHAR(7) NOT NULL,
    CHANNEL CHAR(3) NOT NULL,
    AMOUNT DECIMAL(9,2) NOT NULL,
    PRIMARY KEY (PAYMENT_ID),
    UNIQUE (TXN_ID),
    FOREIGN KEY (TXN_ID) REFERENCES "TRANSACTION" (TXN_ID),
    FOREIGN KEY (BATCH_ID) REFERENCES PAYMENT_BATCH (BATCH_ID)
);
CREATE TABLE CARD (
    CARD_ID CHAR(8) NOT NULL,
    ACCOUNT_NO CHAR(10) NOT NULL,
    INVALID_PAN CHAR(16) NOT NULL,
    EXPIRY_DATE DATE NOT NULL,
    STATUS CHAR(1) NOT NULL CHECK (STATUS IN ('A', 'B')),
    PRIMARY KEY (CARD_ID),
    UNIQUE (INVALID_PAN),
    FOREIGN KEY (ACCOUNT_NO) REFERENCES ACCOUNT (ACCOUNT_NO)
);
CREATE TABLE CARD_AUTH (
    CARD_ID CHAR(8) NOT NULL,
    AUTH_SEQ INTEGER NOT NULL,
    AUTH_AT TIMESTAMP NOT NULL,
    AMOUNT DECIMAL(9,2) NOT NULL,
    DECISION CHAR(1) NOT NULL CHECK (DECISION IN ('A', 'D')),
    PRIMARY KEY (CARD_ID, AUTH_SEQ),
    FOREIGN KEY (CARD_ID) REFERENCES CARD (CARD_ID)
);
CREATE TABLE FEE_SCHEDULE (
    PRODUCT_ID CHAR(4) NOT NULL,
    FEE_CODE CHAR(4) NOT NULL,
    EFFECTIVE_DATE DATE NOT NULL,
    AMOUNT DECIMAL(7,2) NOT NULL,
    PRIMARY KEY (PRODUCT_ID, FEE_CODE, EFFECTIVE_DATE),
    FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT (PRODUCT_ID)
);
CREATE TABLE GL_ACCOUNT (
    GL_CODE CHAR(4) NOT NULL,
    DESCRIPTION VARCHAR(32) NOT NULL,
    PRIMARY KEY (GL_CODE)
);
CREATE TABLE GL_POSTING (
    TXN_ID CHAR(9) NOT NULL,
    LINE_NO SMALLINT NOT NULL,
    GL_CODE CHAR(4) NOT NULL,
    AMOUNT DECIMAL(9,2) NOT NULL,
    PRIMARY KEY (TXN_ID, LINE_NO),
    FOREIGN KEY (TXN_ID) REFERENCES "TRANSACTION" (TXN_ID),
    FOREIGN KEY (GL_CODE) REFERENCES GL_ACCOUNT (GL_CODE),
    CHECK (LINE_NO IN (1, 2))
);
CREATE TABLE FRAUD_ALERT (
    ALERT_ID CHAR(9) NOT NULL,
    TXN_ID CHAR(9) NOT NULL,
    SEVERITY SMALLINT NOT NULL CHECK (SEVERITY BETWEEN 1 AND 5),
    REASON VARCHAR(32) NOT NULL,
    PRIMARY KEY (ALERT_ID),
    FOREIGN KEY (TXN_ID) REFERENCES "TRANSACTION" (TXN_ID)
);
CREATE INDEX IX_ACCOUNT_CUSTOMER ON ACCOUNT (CUSTOMER_ID, ACCOUNT_NO);
CREATE INDEX IX_TXN_ACCOUNT_DATE ON "TRANSACTION" (ACCOUNT_NO, POSTED_DATE);
CREATE INDEX IX_PAYMENT_BATCH ON PAYMENT (BATCH_ID, PAYMENT_ID);
CREATE INDEX IX_AUTH_TIME ON CARD_AUTH (AUTH_AT, CARD_ID);
CREATE INDEX IX_GL_CODE ON GL_POSTING (GL_CODE, TXN_ID);
