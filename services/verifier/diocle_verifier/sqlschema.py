VERSION = "0.1"
CONTRACT = Path(__file__).resolve().parents[3] / "contracts" / "sql-schema.schema.json"
SQLITE_EXACT_DIGITS = 15
MAX_FAILURES = 20
DB2_CHAR_MAX = 254
_NATIVE_DIGITS = {2: 5, 4: 10, 8: 20}  # decimal digits a 2-, 4- or 8-byte COMP-5 can hold
_USAGE_NAMES = {"packed": " COMP-3", "binary": " COMP", "binary-native": " COMP-5"}
_SIGN_NAMES = {"leading-separate": " SIGN LEADING SEPARATE", "trailing-separate": " SIGN TRAILING SEPARATE",
               "leading": " SIGN LEADING"}


def _snake(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_") or "field"


def _unique(name: str, used: set[str]) -> str:
    candidate, n = name, 1
    while candidate in used:
        n += 1
        candidate = f"{name}_{n}"
    used.add(candidate)
    return candidate


def _precision(f: Field) -> tuple[int, int]:
    """DECIMAL(p,s) for a numeric field; P scaling (negative scale) widens the integer part instead. COMP-5 is sized by
    its bytes: IBM COBOL does not truncate it to its PIC."""
    if f.usage == "binary-native":
        return _NATIVE_DIGITS[f.length], max(f.scale, 0)
    return f.digits + max(f.scale, 0), max(f.scale, 0)


def sql_type(f: Field) -> str:
    if f.kind == "alnum":
        return f"CHAR({f.length})" if f.length <= DB2_CHAR_MAX else f"VARCHAR({f.length})"
    if f.usage == "float":
        return "REAL" if f.length == 4 else "DOUBLE PRECISION"
    return "DECIMAL({},{})".format(*_precision(f))


def cobol_description(spec: dict) -> str:
    """The field's PIC, usage and sign as COBOL states them."""
    if spec["kind"] == "alnum":
        return f"PIC {spec['edited']} (edited)" if "edited" in spec else f"PIC X({spec['length']})"
    if spec.get("usage") == "float":
        return "COMP-1" if spec.get("bytes", 8) == 4 else "COMP-2"
    digits, scale = spec["digits"], spec["scale"]
    if scale < 0:
        pic = f"9({digits + scale})P({-scale})"
    else:
        pic = (f"9({digits})" if digits else "") + (f"V9({scale})" if scale else "")
    pic = ("S" if spec.get("signed") else "") + pic
    return f"PIC {pic}{_USAGE_NAMES.get(spec.get('usage', 'display'), '')}{_SIGN_NAMES.get(spec.get('sign', ''), '')}"


@dataclass
class Table:
    name: str
    record: str
    fields: list[Field]
    columns: list[dict]
    notes: list[str]
    fmt: str
    dd: str | None = None
    direction: str | None = None
    ddl: str = ""
    sqlite_ddl: str = ""

    @property
    def length(self) -> int:
        return record_length(self.fields)


def _comment(text: str) -> str:
    return re.sub(r"[\x00-\x1f\x7f]", " ", text)  # a newline would end the SQL comment


def _ddl(table: Table, *, sqlite: bool = False) -> str:
    where = f" of DD {table.dd}" + (f" ({table.direction})" if table.direction else "") if table.dd else ""
    lines = [_comment(f"-- {table.record}: record{where}, {table.length} bytes. Generated by Diocle from the copybook "
                      "layout; no model involved.")]
    lines += [_comment(f"-- {note}") for note in table.notes]
    lines.append(f'CREATE TABLE "{table.name}" (')
    body = [('"rec_no" INTEGER PRIMARY KEY', "record order in the file")]
    for c, f in zip(table.columns, table.fields):
        kind = c["sqlType"]
        if sqlite and kind.startswith("DECIMAL") and _precision(f)[0] > SQLITE_EXACT_DIGITS:
            kind = "TEXT"  # SQLite NUMERIC keeps 15 significant digits; text keeps them all
        check = f' CHECK ("{c["column"]}" >= 0)' if f.kind == "numeric" and not f.signed and f.usage != "float" else ""
        last = c["offset"] + c["length"] - 1
        comment = f'{c["field"]} {c["cobol"]}, bytes {c["offset"]}-{last}'
        if c.get("redefinedBy"):
            comment += "; also read as " + ", ".join(c["redefinedBy"]) + " (REDEFINES)"
        body.append((f'"{c["column"]}" {kind} NOT NULL{check}', comment))
    for i, (sql, comment) in enumerate(body):
        lines.append(f"  {sql}{',' if i < len(body) - 1 else ''}  -- {_comment(comment)}")
    lines.append(");")
    return "\n".join(lines) + "\n"


def build_table(spec: dict, *, dd: str | None = None, direction: str | None = None,
                used_tables: set[str] | None = None) -> Table:
    """One SQL table for a record layout (the analyzer's layout dict, as in sample.json)."""
    used_tables = used_tables if used_tables is not None else set()
    fields = load_fields(spec)
    stored = [s for s in spec["fields"] if not s.get("redefines")]  # load_fields keeps these, in this order
    redefiners: dict[str, list[str]] = {}
    for s in spec["fields"]:
        if s.get("redefines"):
            redefiners.setdefault(s["redefines"], [])
            if s["name"] not in redefiners[s["redefines"]]:
                redefiners[s["redefines"]].append(s["name"])
    used, columns, offset = {"rec_no"}, [], 1
    for s, f in zip(stored, fields):
        column = {"column": _unique(_snake(f.name), used), "field": f.name, "sqlType": sql_type(f),
                  "offset": offset, "length": f.length, "cobol": cobol_description(s)}
        if f.name in redefiners:
            column["redefinedBy"] = redefiners[f.name]
        columns.append(column)
        offset += f.length
    notes = []
    for base, names in redefiners.items():
        if base in {f.name for f in fields}:
            notes.append(f"REDEFINES: {', '.join(names)} are another view of {base}'s bytes; stored once, in that column.")
        else:
            notes.append(f"REDEFINES: {', '.join(names)} are another view of group {base}'s bytes; stored once, in the "
                         "columns of its fields.")
    occurs: dict[str, list[dict]] = {}
    for c in columns:
        m = re.match(r"(.+?)\(\d+\)", c["field"])
        if m:
            occurs.setdefault(m.group(1), []).append(c)
    for base, cols in occurs.items():
        notes.append(f"OCCURS: {cols[0]['field']} .. {cols[-1]['field']} ({len(cols)} entries) stored as columns "
                     f"{cols[0]['column']} .. {cols[-1]['column']}.")
    name = _snake(spec.get("record", "record"))
    name = _unique(f"{name}_{_snake(dd)}" if name in used_tables and dd else name, used_tables)
    table = Table(name, spec.get("record", "?"), fields, columns, notes, record_format(spec), dd, direction)
    table.ddl, table.sqlite_ddl = _ddl(table), _ddl(table, sqlite=True)
    return table


def _show(raw: str) -> str:
    return repr(raw) if raw.isprintable() else "x'" + raw.encode("latin-1").hex().upper() + "'"


def _decode(f: Field, raw: str) -> Decimal | str:
    """One field's value from its bytes; a numeric field that does not parse stays raw (and cannot be stored)."""
    if f.kind == "alnum":
        return raw
    try:
        return _parse_value(f, raw)
    except Exception:
        return raw if raw.isprintable() else _show(raw)


def _encode(f: Field, value: Decimal | str) -> str:
    if f.usage == "binary-native":  # full byte range, as COBOL stores it
        return int(Decimal(value).scaleb(f.scale)).to_bytes(f.length, "little", signed=f.signed).decode("latin-1")
    return format_value(f, value)


def _fit_error(sql: str, value: Decimal | str) -> str | None:
    """Why the published column type cannot hold the value, judged from the type as written in the DDL."""
    m = re.fullmatch(r"(?:VAR)?CHAR\((\d+)\)", sql)
    if m:
        return None if len(value) <= int(m.group(1)) else f"is {len(value)} bytes, longer than {sql}"
    if isinstance(value, str):
        return f"holds {value}, which is not a valid number for its PIC; a numeric column cannot store it"
    if not value.is_finite():
        return f"holds {value}, which a {sql} column cannot store as a number"
    m = re.fullmatch(r"DECIMAL\((\d+),(\d+)\)", sql)
    if m:
        p, s = int(m.group(1)), int(m.group(2))
        if value != value.quantize(Decimal(1).scaleb(-s)):
            return f"holds {value}, which has more decimal places than {sql}"
        if abs(value) >= Decimal(10) ** (p - s):
            return f"holds {value}, which does not fit {sql}"
    return None


def _to_sql(f: Field, value: Decimal | str) -> object:
    if f.kind == "alnum":
        return value
    return float(value) if f.usage == "float" else format(value, "f")


def _from_sql(f: Field, value: object) -> Decimal | str:
    if f.kind == "alnum":
        return value
    return Decimal(repr(value)) if isinstance(value, float) else Decimal(str(value))


def round_trip(table: Table, sources: list[tuple[str, list[str]]]) -> dict:
    """Check every record against the published column types, load it into SQLite through the table, read it back,
    re-encode it field by field and compare byte for byte. Fields are handled by position, never by name: a record
    can hold several fields with the same name (FILLER)."""
    db = sqlite3.connect(":memory:")
    failures: list[dict] = []
    expected: dict[int, tuple[str, str]] = {}
    n = identical = 0

    def fail(record: int, label: str, name: str | None, detail: str) -> None:
        failures.append({"record": record, "source": label, "field": name, "detail": detail})

    try:
        db.execute(table.sqlite_ddl)
        for label, records in sources:
            for record in records:
                n += 1
                original = record if table.fmt == "fixed" else record.rstrip("\r\n").ljust(table.length)
                if len(original) != table.length:
                    fail(n, label, None, f"record is {len(original)} bytes, the layout describes {table.length}")
                    continue
                row, pos, problem = [n], 0, None
                for f, column in zip(table.fields, table.columns):
                    value = _decode(f, original[pos : pos + f.length])
                    pos += f.length
                    problem = _fit_error(column["sqlType"], value)
                    if problem:
                        fail(n, label, f.name, f"{f.name} {problem}")
                        break
                    row.append(_to_sql(f, value))
                if problem:
                    continue
                try:
                    db.execute(f'INSERT INTO "{table.name}" VALUES ({", ".join("?" * len(row))})', row)
                except sqlite3.Error as e:
                    fail(n, label, None, f"SQLite refused the row: {e}")
                    continue
                expected[n] = (label, original)
        for row in db.execute(f'SELECT * FROM "{table.name}" ORDER BY rec_no'):
            label, original = expected[row[0]]
            pos = 0
            for f, value in zip(table.fields, row[1:]):
                a = original[pos : pos + f.length]
                pos += f.length
                try:
                    b = _encode(f, _from_sql(f, value))
                except (ValueError, OverflowError, ArithmeticError) as e:
                    fail(row[0], label, f.name, f"{f.name}: cannot re-encode {value!r}: {e}")
                    break
                if a != b:
                    fail(row[0], label, f.name, f"{f.name}: original {_show(a)} came back {_show(b)}")
                    break
            else:
                identical += 1
    finally:
        db.close()
    failures.sort(key=lambda x: x["record"])
    return {"records": n, "identical": identical, "sources": [label for label, _ in sources],
            "failures": failures[:MAX_FAILURES]}


def schema_report(meta: dict, *, seed: int = 1026, random_count: int = 200,
                  data: dict[str, list[tuple[str, list[str]]]] | None = None) -> dict:
    """Tables for every file layout of a sample, each with its round-trip proof (contracts/sql-schema.schema.json)."""
    used: set[str] = set()
    tables = []
    for spec in file_specs(meta):
        table = build_table(spec["layout"], dd=spec.get("dd"), direction=spec.get("direction"), used_tables=used)
        cases = generate_cases(table.fields, seed=seed, random_count=random_count)
        sources = [(f"generated (seed {seed})", [c.record for c in cases])] + (data or {}).get(spec.get("dd"), [])
        tables.append({"dd": table.dd, "direction": table.direction, "table": table.name, "record": table.record,
                       "recordLength": table.length, "columns": table.columns, "notes": table.notes,
                       "ddl": table.ddl, "roundTrip": round_trip(table, sources)})
    records = sum(t["roundTrip"]["records"] for t in tables)
    identical = sum(t["roundTrip"]["identical"] for t in tables)
    return {"version": VERSION, "program": meta.get("program"), "ddl": "\n".join(t["ddl"] for t in tables),
            "tables": tables, "summary": {"tables": len(tables), "records": records, "identical": identical,
                                          "passed": bool(tables) and records == identical}}


def validate_report(report: dict) -> None:
    import jsonschema

    jsonschema.validate(report, json.loads(CONTRACT.read_text()))


def _load_data(meta: dict, args: list[str], ebcdic: bool) -> dict[str, list[tuple[str, list[str]]]]:
    layouts = {s["dd"]: s["layout"] for s in file_specs(meta)}
    data: dict[str, list[tuple[str, list[str]]]] = {}
    for arg in args:
        dd, _, path = arg.partition("=")
        if dd not in layouts or not path:
            raise SystemExit(f"--data {arg}: expected DD=PATH with DD one of {', '.join(layouts)}")
        fields = load_fields(layouts[dd])
        length = record_length(fields)
        if ebcdic:
            raw = Path(path).read_bytes()
            records = [r.decode("latin-1") for r in convert_file(raw, fields, length)]
        else:
            records = read_records(Path(path), record_format(layouts[dd]), length)
        data.setdefault(dd, []).append((Path(path).name + (" (EBCDIC)" if ebcdic else ""), records))
    return data


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="diocle_verifier.sqlschema", description=__doc__.split("\n\n")[0])
    parser.add_argument("sample_dir", type=Path)
    parser.add_argument("--out", type=Path, help="write schema.sql and sql-schema.json here")
    parser.add_argument("--seed", type=int, default=1026)
    parser.add_argument("--random", type=int, default=200, help="seeded random records per table (default 200)")
    parser.add_argument("--data", action="append", default=[], metavar="DD=PATH",
                        help="also round-trip the records of a data file (repeatable)")
    parser.add_argument("--ebcdic", action="store_true", help="--data files are mainframe EBCDIC, fixed length")
    args = parser.parse_args(argv)

    meta = json.loads((args.sample_dir / "sample.json").read_text())
    report = schema_report(meta, seed=args.seed, random_count=args.random,
                           data=_load_data(meta, args.data, args.ebcdic))
    validate_report(report)
    if args.out:
        args.out.mkdir(parents=True, exist_ok=True)
        (args.out / "schema.sql").write_text(report["ddl"])
        (args.out / "sql-schema.json").write_text(json.dumps(report, indent=2) + "\n")
    else:
        print(report["ddl"])
    for t in report["tables"]:
        rt = t["roundTrip"]
        print(f"{t['table']}: {rt['identical']}/{rt['records']} records came back byte for byte "
              f"({', '.join(rt['sources'])})", file=sys.stderr)
        for failure in rt["failures"][:5]:
            print(f"  record {failure['record']} [{failure.get('source', '')}]: {failure['detail']}", file=sys.stderr)
    s = report["summary"]
    print(f"{'PASS' if s['passed'] else 'FAIL'}  {s['identical']}/{s['records']} records, {s['tables']} tables",
          file=sys.stderr)
    return 0 if s["passed"] else 1


if __name__ == "__main__":
    sys.exit(main())
