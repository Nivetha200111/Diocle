"""Copybook record layouts as SQL tables, proven by a byte-exact round trip through SQLite.

Deterministic, no model calls. Each elementary field becomes one column, in record order, so a row holds every byte
of its record: alphanumeric and edited fields as CHAR(n) (VARCHAR(n) above DB2's 254-byte CHAR limit), zoned, packed
and binary numerics as DECIMAL(p,s) with the PIC's precision, COMP-5 as wide as its bytes (it is not truncated to its
PIC), COMP-1/COMP-2 as REAL/DOUBLE PRECISION. FILLER is kept (it can hold data). REDEFINES views share bytes another
column already stores, so they are listed, not stored twice; OCCURS entries become numbered columns. A rec_no column
keeps the file's record order.

The proof: records (PIC boundaries and seeded random values, plus any data files given) are checked against each
column's published type (length for CHAR, precision and scale for DECIMAL), inserted into an SQLite copy of the
tables, read back, re-encoded field by field and compared byte for byte with the originals. SQLite does not enforce
declared sizes and keeps only 15 significant digits in NUMERIC columns, which is why the type check happens before the
insert and a DECIMAL wider than 15 digits is TEXT in the SQLite copy; PostgreSQL and DB2 hold DECIMAL(p,s) exactly.
Generated records are written by the same codec, so they test the column mapping; data files (--data) test real bytes.

CLI: python -m diocle_verifier.sqlschema SAMPLE_DIR [--out DIR] [--data DD=PATH ...] [--ebcdic]
"""

