"""Generate diocle_verifier/diag_words.py: the words GnuCOBOL's own diagnostics are made of.

  python3 scripts/gen_diag_words.py /path/to/cobc > diocle_verifier/diag_words.py

precheck.clean_message lets a word of a compiler diagnostic through only if it is in this list (the reserved words
of `cobc --list-reserved` plus the lowercase words of cobc's own message strings), so a word that a visitor's
source or a COPYed file put into a message never reaches the public reason.
"""

import re
import subprocess
import sys

cobc = sys.argv[1]
reserved = subprocess.run([cobc, "--list-reserved"], capture_output=True, text=True).stdout.splitlines()[1:]
words = {ln.split()[0].lower() for ln in reserved if ln.strip() and re.match(r"^[A-Za-z0-9-]+\s", ln)}
binary = subprocess.run(["strings", "-a", cobc], capture_output=True, text=True).stdout
for line in binary.splitlines():
    if " " in line and re.search(r"[a-z]{3}", line) and len(line) < 200 and not line.startswith(("/", "-")):
        words |= {w.lower() for w in re.findall(r"[A-Za-z][A-Za-z-]{1,24}", line)}
print('"""Generated by scripts/gen_diag_words.py from cobc 3.2: do not edit by hand."""\n')
print("WORDS = frozenset(\"\"\"")
print(" ".join(sorted(words)))
print('""".split())')
